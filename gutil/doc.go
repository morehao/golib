// Package gutil 提供跨业务复用的通用工具函数集合。
//
// # 一、准入边界（什么能放进 gutil）
//
// gutil 只接收同时满足以下条件的「纯函数」：
//
//  1. 无状态：不持有、不修改任何包级可变状态，不依赖 init 顺序；
//  2. 无外部依赖：不依赖配置、数据库、缓存等需注入的依赖；不访问网络/进程等
//     需要跨进程协作的资源（触达本地文件系统、执行本机 shell、本机网络探测这类
//     「无外部服务依赖、无状态」的操作可以，见下方「边界补充」）；
//  3. 足够通用：在仓库中至少能被 3 个不同调用场景复用。只被一处使用的函数，
//     请留在调用方所在包。
//
// # 二、什么不能放进 gutil
//
// 一旦引入「领域概念」就不得放入 gutil，例如：
//
//   - 承载业务语义的类型/操作，如货币 Money、订单金额、业务校验规则；
//   - 需要配置、DB、缓存、HTTP 客户端等依赖才能工作的行为；
//   - 只服务单一业务模块的私有逻辑。
//
// 这些应放到更贴近领域的专门包（如具体业务模块、gsetting、storage 等）。
//
// # 三、新增函数前自检
//
// 在往 gutil 添加函数前，请先回答：
//
//	「为什么不做成更专门的包？」
//
// 若答案是「它只服务某一块业务」「它需要某些依赖」「它只被一两个地方用到」，
// 那它就不属于 gutil，应放进对应领域包。只有当它能同时满足上述三条准入边界时，
// 才允许加入 gutil。
//
// # 四、已知的边界与演进计划
//
// 1) time.go —— 业务时间函数未来可能独立为 gtime
//
//	time.go 中部分函数带有偏业务语义的「时间区间/耗时」概念，例如
//	FormatRequestTime、GetRequestCost、GetWeekRange、GetMonthRange 等。
//	它们目前尚属轻量、通用，暂留在 gutil；但若这类时间区间/耗时函数继续膨胀，
//	计划将其拆分到独立的 gtime 包，以便 gutil 保持「无业务语义」的纯净边界。
//	（本文件仅登记计划，不改变任何现有函数实现或签名。）
//
// 2) random.go GenUUID 与 gcrypto 的职责不重叠
//
//	random.go 的 GenUUID 生成 UUID(v7) 字符串，用于请求 ID、任务运行 ID 等
//	「唯一标识」场景；gcrypto.GenerateRandomBytes（见 gcrypto 包）用于生成
//	加密用途的随机字节。两者用途不同：前者是标识生成，后者是密码学随机源，
//	职责不重叠。请注意不要在安全敏感的随机场景误用 GenUUID，也不要把加密随机
//	需求塞进 gutil。
//
// 3) 边界补充：本地 IO 与系统工具
//
//	file.go（本地文件检查/读写）、zip.go（本地 zip 打包/解压）、shell.go（本机
//	执行 shell 命令）、net.go（本机 IP 获取、IPv4 转换、本机端口探测）均属
//	「无状态、无外部服务依赖、只触达本机资源」的工具函数，放在 gutil 合理。
//	判定红线仍然是：是否需要注入配置/客户端、是否依赖外部服务（数据库/缓存/
//	消息队列/远端 HTTP 等）。一旦需要，就不是 gutil，应放进对应领域包
//	（如 storage、dbaccess、gcache、protocol 等）。
